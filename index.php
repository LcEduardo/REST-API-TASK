<?php

require __DIR__ . "/vendor/autoload.php";
require __DIR__ . "/config/database.php";

use App\Auth\ApiKeyAuth;
use App\Auth\Authenticator;
use App\Auth\JwtAuth;
use App\Controller\ControllerAuth;
use App\Controller\ControllerBoss;
use App\Controller\ControllerTask;
use App\Controller\ControllerWorker;
use App\Model\Boss;
use App\Model\Task;
use App\Model\Worker;

$Worker = new Worker($db);
$controllerWorker = new ControllerWorker($Worker);

$Boss = new Boss($db);
$controllerBoss = new ControllerBoss($Boss);

$Task = new Task($db);
$controllerTask = new ControllerTask($Task, $controllerWorker, $controllerBoss);

header('Content-Type: application/json');

// Key sent in the X-API-Key header -> role ('boss' or 'worker').
// $Worker lets keys generated by POST /worker authenticate too (looked up by hash).
$apiKeys = new ApiKeyAuth([
    'boss'   => $_ENV['API_SECRET_KEY_BOSS'] ?? null,
    'worker' => $_ENV['API_SECRET_KEY_WORKER'] ?? null,
], $Worker);

// JWTs are only enabled when JWT_SECRET is set. A secret that is too short throws here on purpose:
// a misconfigured secret must fail loudly instead of signing weak tokens.
$jwtSecret = $_ENV['JWT_SECRET'] ?? '';
$jwt = $jwtSecret === ''
    ? null
    : new JwtAuth($jwtSecret, (int) ($_ENV['JWT_TTL'] ?? 3600));

$controllerAuth = new ControllerAuth($jwt);
$authenticator  = new Authenticator($apiKeys, $jwt);

// Calculated before the route table so the handlers can check the role.
// The API key lookup hits the database; if it fails, respond 500 instead of a fatal error
$authFailed = false;
try {
    $identity = $authenticator->authenticate(
        // Apache only exposes the header as REDIRECT_HTTP_AUTHORIZATION after a rewrite
        $_SERVER['HTTP_AUTHORIZATION'] ?? $_SERVER['REDIRECT_HTTP_AUTHORIZATION'] ?? null,
        $_SERVER['HTTP_X_API_KEY'] ?? null
    );
} catch (PDOException $e) {
    $identity = null;
    $authFailed = true;
}
$role       = $identity['role'] ?? null;
$authMethod = $identity['method'] ?? null;

$routes   = (require __DIR__ . '/config/routes.php')(
    $controllerTask, $controllerWorker, $controllerBoss, $controllerAuth, $role, $authMethod
);
$segments = parseSegments($_SERVER['SCRIPT_NAME'], $_SERVER['REQUEST_URI']);
$response = dispatch($routes, $_SERVER['REQUEST_METHOD'], $segments, $role, $authFailed);

respond($response['status'], $response['body'], $response['headers'] ?? []);
