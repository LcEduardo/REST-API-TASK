<?php

require __DIR__ . "/vendor/autoload.php";
require __DIR__ . "/config/database.php";

use App\Auth\ApiKeyAuth;
use App\Controller\ControllerBoss;
use App\Controller\ControllerTask;
use App\Controller\ControllerWorker;
use App\Model\Boss;
use App\Model\Task;
use App\Model\Worker;

$Worker = new Worker($db);
$controllerWorker = new ControllerWorker($Worker);

$Boss = new Boss($db);
$controllerBoss = new ControllerBoss($Boss);

$Task = new Task($db);
$controllerTask = new ControllerTask($Task, $controllerWorker, $controllerBoss);

header('Content-Type: application/json');

// Key sent in the X-API-Key header -> role ('boss' or 'worker').
// Calculated before the route table so the handlers can check the role.
// $Worker lets keys generated by POST /worker authenticate too (looked up by hash).
$auth = new ApiKeyAuth([
    'boss'   => $_ENV['API_SECRET_KEY_BOSS'] ?? null,
    'worker' => $_ENV['API_SECRET_KEY_WORKER'] ?? null,
], $Worker);

// The worker lookup hits the database; if it fails, respond 500 instead of a fatal error
$authFailed = false;
try {
    $role = $auth->roleFor($_SERVER['HTTP_X_API_KEY'] ?? null);
} catch (PDOException $e) {
    $role = null;
    $authFailed = true;
}

$routes   = (require __DIR__ . '/config/routes.php')($controllerTask, $controllerWorker, $controllerBoss, $role);
$segments = parseSegments($_SERVER['SCRIPT_NAME'], $_SERVER['REQUEST_URI']);
$response = dispatch($routes, $_SERVER['REQUEST_METHOD'], $segments, $role, $authFailed);

respond($response['status'], $response['body'], $response['headers'] ?? []);
